create or replace function public.assign_order_display_code()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_prefix text := '';
  v_digits integer := 4;
begin
  if new.daily_queue_number is null then
    raise exception 'Daily queue number was not assigned before order display code generation';
  end if;

  select coalesce(s.order_number_prefix, ''),
         greatest(2, least(8, coalesce(s.order_number_digits, 4)))
    into v_prefix, v_digits
  from public.restaurant_settings s
  where s.id = 'restaurant';

  new.order_code := v_prefix || lpad(new.daily_queue_number::text, v_digits, '0');
  return new;
end;
$$;

drop trigger if exists zzzz_assign_order_display_code on public.orders;
create trigger zzzz_assign_order_display_code
before insert on public.orders
for each row execute function public.assign_order_display_code();

update public.orders o
set order_code = coalesce(
  (select coalesce(s.order_number_prefix, '') ||
          lpad(o.daily_queue_number::text,
               greatest(2, least(8, coalesce(s.order_number_digits, 4))), '0')
   from public.restaurant_settings s where s.id='restaurant'),
  lpad(o.daily_queue_number::text, 4, '0')
)
where o.order_code is null and o.daily_queue_number is not null;

comment on column public.orders.order_code is
  'Customer-facing order number generated by database from daily_queue_number and shared restaurant settings.';
