-- Periodic physical stock counts with audited, atomic reconciliation.
begin;
create table if not exists public.inventory_stock_counts (
 id uuid primary key default gen_random_uuid(),
 count_number bigint generated by default as identity unique,
 count_date date not null default current_date,
 notes text not null default '',
 item_count integer not null default 0,
 discrepancy_count integer not null default 0,
 total_discrepancy_cost numeric(14,2) not null default 0,
 created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);
create table if not exists public.inventory_stock_count_items (
 id uuid primary key default gen_random_uuid(),
 count_id uuid not null references public.inventory_stock_counts(id) on delete cascade,
 material_id uuid not null references public.inventory_materials(id) on delete restrict,
 system_quantity numeric(14,3) not null,
 counted_quantity numeric(14,3) not null check(counted_quantity>=0),
 difference_quantity numeric(14,3) generated always as (counted_quantity-system_quantity) stored,
 unit_cost numeric(14,2) not null default 0,
 difference_cost numeric(14,2) generated always as (round((counted_quantity-system_quantity)*unit_cost,2)) stored,
 created_at timestamptz not null default now(),
 unique(count_id,material_id)
);
create index if not exists inventory_stock_counts_date_idx on public.inventory_stock_counts(count_date desc,created_at desc);
create index if not exists inventory_stock_count_items_count_idx on public.inventory_stock_count_items(count_id);
alter table public.inventory_stock_counts enable row level security;
alter table public.inventory_stock_count_items enable row level security;
drop policy if exists inventory_stock_counts_admin_all on public.inventory_stock_counts;
create policy inventory_stock_counts_admin_all on public.inventory_stock_counts for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists inventory_stock_count_items_admin_all on public.inventory_stock_count_items;
create policy inventory_stock_count_items_admin_all on public.inventory_stock_count_items for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
grant select on public.inventory_stock_counts,public.inventory_stock_count_items to authenticated;
revoke insert,update,delete on public.inventory_stock_counts,public.inventory_stock_count_items from authenticated;

create or replace function public.admin_complete_inventory_count(p_counts jsonb,p_notes text default '')
returns uuid language plpgsql security definer set search_path='' as $$
declare
 v_count_id uuid; v_item jsonb; v_material_id uuid; v_counted numeric(14,3);
 v_system numeric(14,3); v_cost numeric(14,2); v_delta numeric(14,3);
 v_items integer:=0; v_discrepancies integer:=0; v_total_cost numeric(14,2):=0;
begin
 if not public.is_admin() then raise exception 'Administrator access required' using errcode='42501'; end if;
 if p_counts is null or jsonb_typeof(p_counts)<>'array' or jsonb_array_length(p_counts)=0 then
   raise exception 'At least one material count is required' using errcode='22023';
 end if;
 if exists(select 1 from jsonb_array_elements(p_counts) x where nullif(x->>'material_id','') is null or nullif(x->>'counted_quantity','') is null) then
   raise exception 'Each count requires material and quantity' using errcode='22023';
 end if;
 if exists(select 1 from jsonb_array_elements(p_counts) x where (x->>'counted_quantity')::numeric<0) then
   raise exception 'Counted quantity cannot be negative' using errcode='22023';
 end if;
 if (select count(*) from jsonb_array_elements(p_counts))<>(select count(distinct x->>'material_id') from jsonb_array_elements(p_counts) x) then
   raise exception 'Duplicate material in count' using errcode='22023';
 end if;
 insert into public.inventory_stock_counts(notes,created_by) values(coalesce(p_notes,''),(select auth.uid())) returning id into v_count_id;
 for v_item in select value from jsonb_array_elements(p_counts) order by value->>'material_id' loop
   v_material_id := (v_item->>'material_id')::uuid;
   v_counted := (v_item->>'counted_quantity')::numeric;
   select quantity_on_hand,unit_cost into v_system,v_cost from public.inventory_materials where id=v_material_id and is_active=true for update;
   if not found then raise exception 'Material % is missing or inactive',v_material_id using errcode='22023'; end if;
   v_delta := v_counted-v_system;
   insert into public.inventory_stock_count_items(count_id,material_id,system_quantity,counted_quantity,unit_cost)
   values(v_count_id,v_material_id,v_system,v_counted,v_cost);
   v_items:=v_items+1;
   if v_delta<>0 then
     v_discrepancies:=v_discrepancies+1;
     v_total_cost:=v_total_cost+round(v_delta*v_cost,2);
     perform public.admin_adjust_inventory(v_material_id,v_delta,'تطبیق شمارش دوره‌ای انبار شماره '||v_count_id::text);
   end if;
 end loop;
 update public.inventory_stock_counts set item_count=v_items,discrepancy_count=v_discrepancies,total_discrepancy_cost=v_total_cost where id=v_count_id;
 return v_count_id;
end; $$;
revoke all on function public.admin_complete_inventory_count(jsonb,text) from public,anon;
grant execute on function public.admin_complete_inventory_count(jsonb,text) to authenticated;
commit;